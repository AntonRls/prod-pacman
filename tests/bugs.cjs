const assert = require('node:assert/strict');
const { boot } = require('./rendering.cjs');
const app = boot();
const run = app.run;
const value = code => JSON.parse(run('JSON.stringify(' + code + ')'));
run('cols = 31; rows = 31; map = Array.from({length: rows}, (_, y) => Array.from({length: cols}, (_, x) => x === 0 || y === 0 || x === cols - 1 || y === rows - 1 ? String.fromCharCode(35) : String.fromCharCode(46))); resetActors(); totalDots = 244; dots = new Map(Array.from({length: 244}, (_, i) => [String(i), {}])); bugPhase = 1; player = actor(10, 10, Object.keys(DIRS)[3])');
assert.deepEqual(value('bugTarget(bugs[0])'), { x: 10, y: 10 });
assert.deepEqual(value('bugTarget(bugs[1])'), { x: 14, y: 10 });
run('player.direction = Object.keys(DIRS)[0]');
assert.deepEqual(value('bugTarget(bugs[1])'), { x: 6, y: 6 }, 'Pinky preserves the upward targeting quirk');
run('bugs[0].x = 3; bugs[0].y = 4');
assert.deepEqual(value('bugTarget(bugs[2])'), { x: 13, y: 12 }, 'Inky doubles the Blinky-to-ahead vector');
run('bugs[3].x = 18; bugs[3].y = 10');
assert.deepEqual(value('bugTarget(bugs[3])'), { x: 10, y: 10 }, 'Clyde chases at exactly eight tiles');
run('bugs[3].x = 17');
assert.deepEqual(value('bugTarget(bugs[3])'), { x: 0, y: 31 }, 'Clyde retreats within eight tiles');
run('bugPhase = 0');
assert.deepEqual(value('bugs.map(bugTarget)'), [{ x: 30, y: -3 }, { x: 0, y: -3 }, { x: 30, y: 31 }, { x: 0, y: 31 }]);
run('bugPhase = 1; player = actor(10, 10, Object.keys(DIRS)[3]); bugs[0].x = 12; bugs[0].y = 12; bugs[0].direction = Object.keys(DIRS)[2]');
assert.equal(run('chooseBugDirection(bugs[0])'), 'up', 'distance ties prefer up before left');
run('bugs[0].reversePending = true');
assert.equal(run('chooseBugDirection(bugs[0])'), 'right', 'mode changes force reversal');
assert.equal(run('bugs[0].reversePending'), false);
run('map = Array.from({length: rows}, () => Array(cols).fill(String.fromCharCode(35))); map[12][12] = map[12][13] = String.fromCharCode(46)');
assert.equal(run('chooseBugDirection(bugs[0])'), 'right', 'dead ends permit the only way out');

const clock = boot();
clock.run('for (let i = 0; i < 45; i++) advanceBugClock()');
assert.equal(clock.run('bugPhase'), 0);
clock.run('advanceBugClock()');
assert.equal(clock.run('bugPhase'), 1, 'scatter changes to chase after seven seconds');
assert.equal(clock.run('bugs.every(bug => bug.reversePending)'), true);
const phaseTime = clock.run('bugPhaseMs');
clock.run('frightenBugs(); for (let i = 0; i < 52; i++) advanceBugClock()');
assert.equal(clock.run('powerTimer'), 0);
assert.equal(clock.run('bugPhaseMs'), phaseTime, 'frightened pauses the schedule');
assert.equal(clock.run('bugs.some(bug => bug.frightened)'), false);
clock.run('for (let i = 0; i < 2000; i++) advanceBugClock()');
assert.equal(clock.run('bugPhase'), 7, 'final chase continues indefinitely');
clock.run('resetActors()');
assert.equal(clock.run('bugPhase'), 0, 'losing a life resets scatter schedule');

const random = boot();
random.run('cols = rows = 15; map = Array.from({length: rows}, () => Array(cols).fill(String.fromCharCode(46))); resetActors(); player = actor(1, 1, Object.keys(DIRS)[3]); bugs[0].x = bugs[0].y = 7; bugs[0].direction = Object.keys(DIRS)[3]; frightenBugs(); bugs[0].reversePending = false');
random.run('Math.random = () => 0');
assert.equal(random.run('chooseBugDirection(bugs[0])'), 'up');
random.run('Math.random = () => .999');
assert.equal(random.run('chooseBugDirection(bugs[0])'), 'right', 'frightened choices include paths away from the target');
random.run('bugs[0].home = {x: 2, y: 7}; map[7][5] = String.fromCharCode(35); returnBugHome(bugs[0])');
assert.equal(random.run('bugs[0].returning'), true);
assert.equal(random.run('bugs[0].returnPath.every(point => !isWall(point.x, point.y))'), true);
random.run('player.x = bugs[0].x; player.y = bugs[0].y; invincible = 0');
const lives = random.run('lives');
random.run('checkCollisions()');
assert.equal(random.run('lives'), lives, 'returning eyes cannot hurt Lotti');
random.run('for (let i = 0; i < 30 && bugs[0].returning; i++) moveBug(bugs[0])');
assert.equal(random.run('bugs[0].returning'), false);
assert.deepEqual(JSON.parse(random.run('JSON.stringify({x: bugs[0].x, y: bugs[0].y})')), { x: 2, y: 7 });
assert.equal(random.run('bugs[0].frightened'), false, 'returned bugs leave frightened mode');
random.run('bugs[1].x = player.x; bugs[1].y = player.y; bugs[1].frightened = true; bugs[1].cooldown = 0; invincible = 0');
const beforeScore = random.run('score');
random.run('checkCollisions()');
assert.equal(random.run('bugs[1].returning'), true, 'caught frightened bug becomes returning eyes');
assert.equal(random.run('score'), beforeScore + 200);
assert.equal(random.run('lives'), lives);
const cache = boot();
cache.run('startGame(); frightenBugs(); draw(1000); draw(1000)');
const fills = cache.metrics.fills;
cache.run('draw(1000)');
assert.equal(cache.metrics.fills, fills, 'classic frightened colors preserve sprite caching');

run('dots = new Map(Array.from({length: 20}, (_, i) => [String(i), {}])); bugPhase = 0');
assert.equal(run('elroyStage()'), 1);
assert.deepEqual(value('bugTarget(bugs[0])'), { x: 10, y: 10 }, 'Elroy chases during scatter');
run('dots = new Map(Array.from({length: 10}, (_, i) => [String(i), {}]))');
assert.equal(run('elroyStage()'), 2);
assert.deepEqual(value('BUG_PROFILES.map(bug => bug.color)'), ['#ff0000', '#ffb8ff', '#00ffff', '#ffb852']);
assert.equal(run('EYES_ART.every(row => row.length === 16)'), true);
run('resetGame(); startGame(); invincible = 10000; for (let i = 0; i < 1000; i++) { tick(); if (bugs.some(bug => isWall(bug.x, bug.y))) throw Error(String.fromCharCode(35)); }');
console.log('PASS: four arcade targets, up-overflow quirk, turn ties, reversal, frightened randomness, mode clock, return eyes, Elroy, colors and 1000 legal simulation steps.');
